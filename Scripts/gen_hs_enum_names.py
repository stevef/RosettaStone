#!/usr/bin/env python3
"""Generate Includes/Rosetta/PlayMode/Loaders/HsEnumNames.hpp.

CardDefs.xml stores CARD_SET, CARDTYPE, CLASS, CARDRACE, RARITY, SPELL_SCHOOL,
MULTI_CLASS_GROUP and FACTION as Blizzard's numeric IDs. RosettaStone's enums
are positional (see Includes/Rosetta/Common/Enums/*.def), so the XML loader
maps number -> name (this table, from python-hearthstone) -> RosettaStone enum
(StrToEnum). Run with a python that has python-hearthstone installed:

    python -I Scripts/gen_hs_enum_names.py Includes/Rosetta/PlayMode/Loaders/HsEnumNames.hpp
"""
import sys
import hearthstone
from hearthstone import enums

ENUMS = ["CardSet", "CardType", "CardClass", "Race", "Rarity", "SpellSchool",
         "MultiClassGroup", "Faction"]

out = sys.argv[1]
lines = [
    "// Generated by Scripts/gen_hs_enum_names.py from python-hearthstone %s."
    % hearthstone.__version__,
    "// Blizzard numeric enum ID -> HearthSim name, for CardDefsXmlLoader.",
    "#ifndef ROSETTASTONE_PLAYMODE_HS_ENUM_NAMES_HPP",
    "#define ROSETTASTONE_PLAYMODE_HS_ENUM_NAMES_HPP",
    "",
    "#include <string_view>",
    "#include <unordered_map>",
    "",
    "namespace RosettaStone::PlayMode::HsEnumNames",
    "{",
]
for name in ENUMS:
    en = getattr(enums, name)
    seen = {}
    for m in en:  # aliases share a value; keep the first (canonical) name
        seen.setdefault(m.value, m.name)
    lines.append("inline const std::unordered_map<int, std::string_view> %s = {" % name)
    for v, n in sorted(seen.items()):
        lines.append('    { %d, "%s" },' % (v, n))
    lines.append("};")
lines += ["}  // namespace RosettaStone::PlayMode::HsEnumNames", "",
          "#endif  // ROSETTASTONE_PLAYMODE_HS_ENUM_NAMES_HPP", ""]
open(out, "w").write("\n".join(lines))
print("wrote", out)
